<h1 class="wp-block-heading has-text-align-center has-xx-large-font-size" style="margin-bottom:var(--wp--preset--spacing--40)">Healing Is Sacred Work</h1>
<!-- /wp:heading -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">We believe that every person carries within them an innate capacity to heal, grow, and rediscover the wholeness that has always been there beneath the layers of conditioning, trauma, and life experience.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">The medicine, the ceremonies, the 4-E Process, and everything we do at Lumina are ultimately in service of that remembering. Not to give you something you do not already possess, but to help remove the obstacles that may have obscured it.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">Healing is not about becoming someone else. It is about returning to what is most authentic within you. It is about meeting yourself with honesty, compassion, and courage, and allowing what no longer serves you to soften, release, and transform.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">We approach this work with humility and deep respect. The experiences that unfold during retreat are often profound, but we do not believe the healing comes from any one person, technique, or medicine. Rather, these are tools that help create the conditions for your own innate wisdom and healing intelligence to emerge.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">Our role is simply to provide a safe and supportive container, to walk beside you on the journey, and to help illuminate the path when it becomes difficult to see.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted"} -->
