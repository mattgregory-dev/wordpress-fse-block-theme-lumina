<h2 class="wp-block-heading">Careful Screening, Because Your Well-Being Comes First</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Not everyone who applies to Lumina is accepted, and that's intentional.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The work we do can be deeply transformative, but it is not the right fit for everyone at every stage of life. Our responsibility is not simply to fill retreat spaces. Our responsibility is to ensure that each person who attends can be supported safely, responsibly, and with the level of care they deserve.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Every guest completes a thorough screening process before acceptance. We take the time to understand your health history, emotional well-being, life circumstances, intentions, and what is calling you to this work. This allows us to determine whether Lumina is the right environment for your unique journey and whether the timing is appropriate.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>If we believe the retreat is not the best fit — or that another form of support would serve you better — we will tell you honestly and compassionately. We view that conversation as an act of care, not exclusion.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>When you are accepted into a Lumina retreat, it means more than simply having a reservation. It means we have thoughtfully considered your application and feel confident that we can support you in a safe, meaningful, and responsible way.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Your trust is something we take seriously, and your well-being will always come before enrollment.</p>
