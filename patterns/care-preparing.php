<h2 class="wp-block-heading">The Work Begins Long Before You Arrive</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>At Lumina, we believe preparation is part of the healing process itself.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Once you are accepted into the retreat, the journey has already begun. In the weeks leading up to your arrival, we will guide you through a carefully designed preparation process intended to help you arrive grounded, clear, and ready for the work ahead.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>This includes following a traditional dieta — a simple set of nutritional and lifestyle guidelines that help reduce distractions, support the body, and create the conditions for a deeper experience. More than a list of restrictions, the dieta is an opportunity to begin slowing down, becoming more intentional, and listening more closely to yourself.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>You will also receive guidance on preparing mentally, emotionally, and spiritually for the retreat. We will help you understand what to expect, how to work with intention, and how to begin identifying the patterns, questions, and areas of your life that are calling for healing and transformation.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Many guests are surprised to discover that meaningful shifts begin before they ever set foot on the retreat grounds. As daily habits become more conscious and attention turns inward, clarity often begins to emerge on its own.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>By the time you arrive at Lumina, you won't be starting the journey. You'll already be on it.</p>
