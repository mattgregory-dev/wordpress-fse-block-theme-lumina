<h2 class="wp-block-heading has-x-large-font-size">These Plants Are Treated as Sacraments</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">The plant medicines we work with are gifts of the earth, held in reverence by Indigenous traditions for generations. We treat them the same way — as sacred medicines and teachers, approached with humility, prayer, intention, and deep respect.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">To us, the word <em>sacrament</em> is not symbolic. It reflects a way of relating to these medicines that is rooted in reverence rather than consumption. A sacrament is something that helps us enter into a deeper relationship with what is sacred — with life, with truth, with the natural world, and ultimately with ourselves. It is not taken casually, recreationally, or for entertainment. It is approached as a sacred act, with intention, responsibility, and a sincere desire to learn, heal, and grow.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">Within a carefully held ceremonial container, these medicines can help illuminate what has been hidden, soften the barriers we place around our hearts, and reveal aspects of ourselves that are asking to be seen, understood, and healed. They can bring us into deeper contact with truth — not always the truth we want to see, but often the truth we most need to encounter.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">We honor the Indigenous lineages that have preserved this wisdom across generations, and we remain deeply grateful for the traditions and elders who have carried these medicines forward. Our commitment is to work with them respectfully, responsibly, and in a way that honors both their sacred origins and the profound role they can play in healing and transformation.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted"} -->
<p class="has-muted-color has-text-color">At Lumina, treating these plants as sacraments means remembering that they are not the destination. They are part of a sacred process — one that invites us into greater awareness, deeper self-understanding, and a more authentic relationship with life itself. When approached in this spirit, the medicine becomes more than an experience. It becomes a doorway to remembrance, healing, and transformation.</p>
