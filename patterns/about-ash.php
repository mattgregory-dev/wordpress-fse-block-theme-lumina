<!-- wp:heading -->
<h2 class="wp-block-heading">Ash Ruiz</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>There are people who teach about awakening, and there are people whose lives become an expression of it.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>For more than three decades, Ash Ruiz has dedicated his life to exploring the nature of consciousness, healing, and human transformation. His journey has taken him through the worlds of music, spirituality, plant medicine, and deep self-inquiry, always guided by a single question: What truly frees us from suffering?</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>What makes Ash unique is not simply the breadth of his experience, but the depth of his presence. Those who work with him often speak of feeling profoundly seen — not judged, analyzed, or fixed, but met with a rare combination of compassion, clarity, and insight. He has an extraordinary ability to recognize the deeper patterns operating beneath a person's story and gently guide them toward the truth that lies underneath.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Ash's path has been anything but conventional. From performing on stages around the world to years spent studying with indigenous elders and shamans in the Amazon, his life has been devoted to understanding both the heights of spiritual awakening and the realities of human healing. For fourteen years, he shared transformative teachings through a conscious music project that touched audiences around the globe. Along the way, he has taught, performed, and shared space with many of the most respected voices in modern spirituality, including Eckhart Tolle, Marianne Williamson, Gangaji, Adyashanti, Byron Katie, Wayne Dyer, Ram Dass, and His Holiness the Dalai Lama.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Yet despite these experiences, Ash's work has never been about collecting teachings, experiences, or spiritual accomplishments. His focus has remained remarkably simple: helping people discover what is already whole and free within themselves.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Over the years, Ash began to recognize that awakening alone does not necessarily resolve the emotional wounds, trauma, and unconscious conditioning that continue to shape our lives. This understanding led him to develop an approach that bridges spiritual realization with embodied healing and deep inquiry — an approach that eventually evolved into the 4-E Elemental Wisdom Process at the heart of Lumina.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>At Lumina, Ash serves as the Spiritual Director and Lead Facilitator, guiding the ceremonies, teachings, and transformational work that define the retreat experience. His gift lies in helping participants move beyond temporary insight and into genuine transformation — where healing is not simply experienced, but embodied.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Those who come to Lumina often arrive seeking answers, healing, or freedom from long-standing patterns. Ash's role is not to provide those answers for them. It is to help create the conditions in which they can discover the truth for themselves.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Because lasting transformation does not come from following another teacher. It comes from awakening the wisdom that has been within you all along.</p>
