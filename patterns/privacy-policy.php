<h3 class="wp-block-heading has-large-font-size" style="margin-top:var(--wp--preset--spacing--40)">Retreat application form</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>When you apply to attend a retreat, we ask for information such as your name, email address, phone number, and answers to questions about your background, your intentions, and your health.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Some of what you share is sensitive. That can include your physical and mental health history, medications you take, and past experiences with substances. We ask for it because plant medicine work is not safe for everyone, and we need this information to decide whether we can serve you safely. We only use it for that purpose.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Applications are reviewed by a person, not by software. No automated system approves or denies you.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We collect this information with your consent, which you give by submitting the form. You can withdraw that consent at any time by contacting us.</p>
